// Package contracttest reads the frozen rich-capture contract corpus
// (contracts/rich-capture) for Companion tests: the wire examples, the
// placement vectors and the native source fixtures, with the fixtures that
// are stored only as recipes regenerated and checked against their digest.
package contracttest

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strconv"
	"strings"
	"testing"
)

// corpusFromSource is where the corpus lies relative to this file, both in
// the repository and in an isolated test copy that keeps companion/ and
// contracts/ side by side.
const corpusFromSource = "../../../contracts/rich-capture"

// Dir is the corpus directory. A missing corpus fails the test: a copy made
// without contracts/ must never pass by testing nothing.
func Dir(t testing.TB) string {
	t.Helper()
	_, source, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("contracttest: cannot locate its own source file")
	}
	dir, err := dirFrom(source)
	if err != nil {
		t.Fatal(err)
	}
	return dir
}

func dirFrom(source string) (string, error) {
	dir := filepath.Clean(filepath.Join(filepath.Dir(source), corpusFromSource))
	if _, err := os.Stat(filepath.Join(dir, "placement-vectors.json")); err != nil {
		return "", fmt.Errorf("contracttest: rich-capture corpus missing at %s (copy contracts/ beside companion/): %w", dir, err)
	}
	return dir, nil
}

// Wire is one example of contracts/rich-capture/wire: a body and the model
// it instantiates. Valid examples carry their HTTP exchange; invalid ones
// say why they are invalid.
type Wire struct {
	Name  string          `json:"-"`
	Model string          `json:"model"`
	HTTP  WireHTTP        `json:"http"`
	Why   string          `json:"why"`
	Body  json.RawMessage `json:"body"`
}

type WireHTTP struct {
	Method         string            `json:"method"`
	Path           string            `json:"path"`
	Status         int               `json:"status"`
	Member         string            `json:"member"`
	RequestHeaders map[string]string `json:"request_headers"`
	BodyBase64     string            `json:"body_base64"`
}

// WireExample reads one valid example by file name.
func WireExample(t testing.TB, name string) Wire {
	t.Helper()
	return readWire(t, filepath.Join(Dir(t), "wire", name))
}

// WireExamples are the valid examples, by file name.
func WireExamples(t testing.TB) []Wire { return readWires(t, filepath.Join(Dir(t), "wire")) }

// InvalidWireExamples are the examples every side must refuse.
func InvalidWireExamples(t testing.TB) []Wire {
	return readWires(t, filepath.Join(Dir(t), "wire", "invalid"))
}

func readWires(t testing.TB, dir string) []Wire {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var wires []Wire
	for _, entry := range entries {
		if entry.Type().IsRegular() && strings.HasSuffix(entry.Name(), ".json") {
			wires = append(wires, readWire(t, filepath.Join(dir, entry.Name())))
		}
	}
	if len(wires) == 0 {
		t.Fatalf("contracttest: no wire examples in %s", dir)
	}
	return wires
}

func readWire(t testing.TB, path string) Wire {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var wire Wire
	if err := json.Unmarshal(data, &wire); err != nil {
		t.Fatalf("contracttest: %s: %v", path, err)
	}
	wire.Name = filepath.Base(path)
	return wire
}

// PlacementVector is one shared device/server placement case.
type PlacementVector struct {
	Name         string   `json:"name"`
	Mode         string   `json:"mode"`
	Roots        []string `json:"roots"`
	Homes        []string `json:"homes"`
	Raw          string   `json:"raw"`
	DevicePlaced string   `json:"device_placed"`
	// ExpectedFixIn names the cards that close a known gap.
	ExpectedFixIn []string `json:"expected_fix_in"`
}

func PlacementVectors(t testing.TB) []PlacementVector {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(Dir(t), "placement-vectors.json"))
	if err != nil {
		t.Fatal(err)
	}
	var file struct {
		Vectors []PlacementVector `json:"vectors"`
	}
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatal(err)
	}
	if len(file.Vectors) == 0 {
		t.Fatal("contracttest: no placement vectors")
	}
	return file.Vectors
}

// SourceDir is the native fixture directory of a surface (claude-code,
// codex-cli, codex-desktop, pi).
func SourceDir(t testing.TB, surface string) string {
	t.Helper()
	dir := filepath.Join(Dir(t), "sources", surface)
	if _, err := os.Stat(filepath.Join(dir, "manifest.json")); err != nil {
		t.Fatalf("contracttest: no manifest for surface %q: %v", surface, err)
	}
	return dir
}

// Recipe is a native body the corpus keeps only as a deterministic recipe,
// regenerated byte for byte.
type Recipe struct {
	// NativePath is where the agent kept the body, as the manifest states it.
	NativePath string
	Body       []byte
}

// Recipes materializes every `stored: false` body of a surface and checks
// each one against its recorded size and sha256.
func Recipes(t testing.TB, surface string) []Recipe {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(SourceDir(t, surface), "manifest.json"))
	if err != nil {
		t.Fatal(err)
	}
	var manifest struct {
		Recipes []struct {
			NativePath string `json:"native_path"`
			Stored     *bool  `json:"stored"`
			Recipe     string `json:"recipe"`
			Bytes      int    `json:"bytes"`
			SHA256     string `json:"sha256"`
		} `json:"recipes"`
	}
	if err := json.Unmarshal(data, &manifest); err != nil {
		t.Fatal(err)
	}
	var recipes []Recipe
	for _, recipe := range manifest.Recipes {
		if recipe.Stored == nil || *recipe.Stored {
			continue
		}
		body, err := materialize(recipe.Recipe)
		if err != nil {
			t.Fatalf("contracttest: %s: %v", recipe.NativePath, err)
		}
		sum := sha256.Sum256(body)
		if len(body) != recipe.Bytes || hex.EncodeToString(sum[:]) != recipe.SHA256 {
			t.Fatalf("contracttest: %s materialized to %d bytes sha256 %x, manifest says %d bytes %s", recipe.NativePath, len(body), sum, recipe.Bytes, recipe.SHA256)
		}
		recipes = append(recipes, Recipe{NativePath: recipe.NativePath, Body: body})
	}
	sort.Slice(recipes, func(i, j int) bool { return recipes[i].NativePath < recipes[j].NativePath })
	return recipes
}

// The corpus' recipes are `python3 -c "print(<literal>*<count>)"`, the
// product optionally parenthesized. They are interpreted here rather than
// run, so tests need no Python and run nothing from the corpus.
var recipeGrammar = regexp.MustCompile(`^python3 -c "print\(\(?'((?:[^'\\]|\\.)*)'\*([0-9]+)\)?\)"$`)

var errUnknownRecipe = errors.New("recipe outside the print(<literal>*<count>) grammar")

func materialize(recipe string) ([]byte, error) {
	match := recipeGrammar.FindStringSubmatch(recipe)
	if match == nil {
		return nil, errUnknownRecipe
	}
	literal, err := strconv.Unquote(`"` + strings.ReplaceAll(match[1], `"`, `\"`) + `"`)
	if err != nil {
		return nil, fmt.Errorf("%w: %v", errUnknownRecipe, err)
	}
	count, err := strconv.Atoi(match[2])
	if err != nil {
		return nil, err
	}
	// print() ends the line.
	return []byte(strings.Repeat(literal, count) + "\n"), nil
}
