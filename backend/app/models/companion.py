import uuid
from datetime import datetime

from sqlalchemy import (
    JSON,
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, UUIDMixin

# Most to least private; `rich` last, so the most private choice still wins.
CONTENT_LEVELS = ("metadata", "standard", "full", "rich")
MAPPING_ORIGINS = ("explicit", "auto_repo")


class CompanionInstallation(Base, UUIDMixin):
    """One capture daemon on one machine, owned by one user.

    The id is generated by the device so enrollment retries are idempotent; the
    device token is server-minted and only its hash is kept.
    """

    __tablename__ = "companion_installations"

    owner_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    name: Mapped[str] = mapped_column(String(200))
    platform: Mapped[str] = mapped_column(String(64))
    token_hash: Mapped[str] = mapped_column(String(64), unique=True)
    token_prefix: Mapped[str] = mapped_column(String(12))
    paused: Mapped[bool] = mapped_column(
        Boolean, default=False, server_default=text("false")
    )
    auto_match_repos: Mapped[bool] = mapped_column(
        Boolean, default=True, server_default=text("true")
    )
    # Harnesses allowed to capture; an empty list disables capture entirely.
    # New installations start with every known harness (see CompanionService).
    enabled_agents: Mapped[list[str]] = mapped_column(
        JSON, default=list, server_default=text("'[]'")
    )
    exclude_globs: Mapped[list[str]] = mapped_column(
        JSON, default=list, server_default=text("'[]'")
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    # Delete this device's sessions this many days after their last event;
    # NULL keeps them until the owner deletes them.
    retention_days: Mapped[int | None] = mapped_column(Integer, nullable=True)
    # The device's latest self-reported status (heartbeat), scrubbed of local
    # paths; stored at most once a minute.
    last_status: Mapped[dict | None] = mapped_column(JSON, nullable=True)
    last_status_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    last_seen_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    revoked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    # What the device announced on its latest policy read; NULL when it
    # announced nothing (an older companion).
    capture_capabilities: Mapped[list[str] | None] = mapped_column(JSON, nullable=True)
    capture_capabilities_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    # Body bytes reserved by this device's sessions in every workspace.
    content_bytes: Mapped[int] = mapped_column(
        BigInteger, default=0, server_default="0"
    )
    # Where the orphan sweep resumes listing this device's stored objects,
    # and when it last swept them.
    content_sweep_cursor: Mapped[str | None] = mapped_column(
        String(1024), nullable=True
    )
    content_swept_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )


class CompanionProjectMapping(Base, UUIDMixin):
    """A local project root routed into one workspace (and optionally a board)."""

    __tablename__ = "companion_project_mappings"
    __table_args__ = (
        UniqueConstraint(
            "installation_id", "root_path", name="uq_companion_mapping_root"
        ),
        CheckConstraint(
            "origin IN ('explicit', 'auto_repo')", name="ck_companion_mapping_origin"
        ),
        CheckConstraint(
            "content_level IN ('metadata', 'standard', 'full', 'rich')",
            name="ck_companion_mapping_content_level",
        ),
        CheckConstraint(
            "(origin = 'auto_repo' AND repo_url_normalized IS NOT NULL) "
            "OR (origin = 'explicit' AND root_path IS NOT NULL)",
            name="ck_companion_mapping_located",
        ),
        Index(
            "uq_companion_mapping_auto_repo",
            "installation_id",
            "repo_url_normalized",
            unique=True,
            postgresql_where=text("origin = 'auto_repo'"),
            sqlite_where=text("origin = 'auto_repo'"),
        ),
    )

    installation_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("companion_installations.id", ondelete="CASCADE"),
        index=True,
    )
    workspace_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True,
    )
    board_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("boards.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    # Null for auto-matched repositories: the device keeps its local root.
    root_path: Mapped[str | None] = mapped_column(String(1024), nullable=True)
    repo_url_normalized: Mapped[str | None] = mapped_column(String(512), nullable=True)
    origin: Mapped[str] = mapped_column(String(16))
    enabled: Mapped[bool] = mapped_column(
        Boolean, default=True, server_default=text("true")
    )
    content_level: Mapped[str] = mapped_column(
        String(16), default="standard", server_default="standard"
    )
    # Server clock: when this mapping last became rich. Content observed long
    # before it is refused; NULL on a rich row grants no bodies.
    rich_since: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
