# Monotonic insertion-order key for the Board Timeline. `created_at` has 1s
# resolution and `id` is a random uuid4, so same-second bursts (one request, one
# runner tick) would otherwise sort randomly and corrupt the FE's forward fold.
#
# On Postgres `seq` is a real BIGINT IDENTITY (DB-assigned): the INSERT must OMIT
# the column so the identity fires. A python-side `default=` is the wrong tool —
# a callable returning None still makes SQLAlchemy BIND `seq = NULL`, and a
# `GENERATED BY DEFAULT` identity rejects an explicit NULL (NotNullViolation).
# So we attach NO column default and instead fill `seq` ONLY on SQLite (tests),
# via the before_insert hook below, since SQLite has no server-side autoincrement
# for a non-PK column. The counter is strictly increasing even within a single
# multi-row flush (a MAX(seq)+1 subquery would collapse to one value).
_seq_lock = threading.Lock()
_seq_counter = itertools.count(1)


class ActivityAction(str, enum.Enum):
    created = "created"
    updated = "updated"
    deleted = "deleted"
    moved = "moved"
    uploaded = "uploaded"
    archived = "archived"
    added_member = "added_member"
    removed_member = "removed_member"
