class Activity(Base, UUIDMixin):
    __tablename__ = "activities"
    __table_args__ = (
        Index("ix_activities_workspace_created", "workspace_id", "created_at"),
        Index("ix_activities_board_created", "board_id", "created_at"),
        Index("ix_activities_board_seq", "board_id", "seq"),
        Index("ix_activities_entity", "entity_type", "entity_id"),
        Index("ix_activities_actor", "actor_id"),
        Index("ix_activities_agent", "agent_id"),
    )

    workspace_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("workspaces.id", ondelete="CASCADE"), index=True
    )
    board_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("boards.id", ondelete="SET NULL"), nullable=True
    )
    actor_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id")
    )
    entity_type: Mapped[ActivityEntityType] = mapped_column(Enum(ActivityEntityType))
    entity_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True))
    action: Mapped[ActivityAction] = mapped_column(Enum(ActivityAction))
    summary: Mapped[str] = mapped_column(String(500), default="")
    # Additive localization contract. Legacy rows intentionally keep both NULL
    # and continue rendering `summary`; new system-authored writes provide a
    # stable semantic key plus data-only interpolation parameters.
    message_key: Mapped[str | None] = mapped_column(String(255), nullable=True)
    message_params: Mapped[dict | None] = mapped_column(JSON, nullable=True)
    changes: Mapped[dict | None] = mapped_column(JSON, nullable=True)
    # Board Timeline (contract v1): role-agnostic entity snapshot before/after
    # this event. NULL for pre-migration rows + events with no meaningful state.
    before_state: Mapped[dict | None] = mapped_column(JSON, nullable=True)
    after_state: Mapped[dict | None] = mapped_column(JSON, nullable=True)
    agent_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("agents.id", ondelete="SET NULL"), nullable=True
    )
    via_api_key: Mapped[str | None] = mapped_column(String(255), nullable=True)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    # Timeline insertion order. NO python default — see the module note above:
    # Postgres lets the IDENTITY assign it (INSERT omits the column); SQLite is
    # filled by `_fill_seq_on_sqlite` below.
    seq: Mapped[int] = mapped_column(BigInteger, Identity(always=False), nullable=False)

    actor: Mapped["User"] = relationship("User", foreign_keys=[actor_id], lazy="noload")

    @property
    def actor_name(self) -> str | None:
        return self.actor.name if self.actor else None

    @property
    def actor_email(self) -> str | None:
        return self.actor.email if self.actor else None


@event.listens_for(Activity, "before_insert")
def _fill_seq_on_sqlite(mapper, connection, target: "Activity") -> None:
    """Assign `seq` from a process-local counter on SQLite only. Postgres leaves
    `target.seq` None so the INSERT omits the column and the IDENTITY assigns it
    (binding an explicit NULL would violate the NOT NULL BY DEFAULT identity)."""
    if connection.dialect.name == "sqlite" and target.seq is None:
        with _seq_lock:
            target.seq = next(_seq_counter)
